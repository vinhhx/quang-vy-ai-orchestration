//! A node project's task worktree is linked to the repo's `node_modules` (symlink), git ignores
//! the link through `info/exclude`, and the worktree stays clean. Everything runs in temp dirs
//! with `git init`; `XDG_DATA_HOME` points at a temp dir so no real worktree folder is touched.

use agent_brain::db::TaskRow;
use agent_brain::projects::Project;
use agent_brain::workspace::{create_task_worktree, ensure_task_root, link_node_modules};
use std::path::{Path, PathBuf};
use std::sync::Mutex;

/// The data dir comes from the environment: one test at a time sets it.
static ENV: Mutex<()> = Mutex::new(());

struct Env {
    _lock: std::sync::MutexGuard<'static, ()>,
    _data: tempfile::TempDir,
    old: Option<std::ffi::OsString>,
}

impl Env {
    fn new() -> Env {
        let lock = ENV.lock().unwrap_or_else(|e| e.into_inner());
        let data = tempfile::tempdir().unwrap();
        let old = std::env::var_os("XDG_DATA_HOME");
        std::env::set_var("XDG_DATA_HOME", data.path());
        Env {
            _lock: lock,
            _data: data,
            old,
        }
    }
}

impl Drop for Env {
    fn drop(&mut self) {
        match &self.old {
            Some(v) => std::env::set_var("XDG_DATA_HOME", v),
            None => std::env::remove_var("XDG_DATA_HOME"),
        }
    }
}

fn git(root: &Path, args: &[&str]) -> String {
    let out = std::process::Command::new("git")
        .arg("-C")
        .arg(root)
        .args(["-c", "user.name=t", "-c", "user.email=t@example.com", "-c", "commit.gpgsign=false"])
        .args(args)
        .env("GIT_TERMINAL_PROMPT", "0")
        .output()
        .unwrap();
    assert!(out.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&out.stderr));
    String::from_utf8_lossy(&out.stdout).to_string()
}

/// A temp repo with one commit. `.gitignore` says `node_modules/` (a folder-only pattern, as in
/// the real project). `package_json`: add a `package.json`; `node_modules`: add the real folder
/// with a binary in `.bin`.
fn project_repo(tmp: &Path, package_json: bool, node_modules: bool) -> PathBuf {
    let repo = tmp.join("repo");
    std::fs::create_dir_all(&repo).unwrap();
    git(&repo, &["init", "-q", "-b", "main"]);
    std::fs::write(repo.join(".gitignore"), "node_modules/\n").unwrap();
    if package_json {
        std::fs::write(repo.join("package.json"), "{}\n").unwrap();
    }
    git(&repo, &["add", "--", ".gitignore"]);
    if package_json {
        git(&repo, &["add", "--", "package.json"]);
    }
    git(&repo, &["commit", "-q", "-m", "init"]);
    if node_modules {
        std::fs::create_dir_all(repo.join("node_modules/.bin")).unwrap();
        std::fs::write(repo.join("node_modules/.bin/x"), "#!/bin/sh\n").unwrap();
    }
    repo.canonicalize().unwrap()
}

fn project(repo: &Path, extra: serde_json::Value) -> Project {
    let mut v = serde_json::json!({
        "id": "web", "path": repo.to_string_lossy(), "name_vi": "web", "aliases": [],
        "type": "code", "repo": null, "profile": "work", "missing": false
    });
    for (k, val) in extra.as_object().unwrap() {
        v[k] = val.clone();
    }
    Project::from_value(&v).unwrap()
}

fn task(slug: &str, workdir: Option<&Path>) -> TaskRow {
    TaskRow {
        id: 7,
        project_id: 1,
        slug: slug.into(),
        title: "x".into(),
        branch: format!("task/{slug}"),
        base_branch: Some("main".into()),
        base_commit: None,
        status: "planned".into(),
        created_at: 0,
        updated_at: 0,
        level: "vua".into(),
        workdir: workdir.map(|w| w.to_string_lossy().to_string()),
    }
}

/// Lines of `<common dir>/info/exclude` of `repo` that are exactly `node_modules`.
fn exclude_count(repo: &Path) -> usize {
    let p = repo.join(".git/info/exclude");
    std::fs::read_to_string(p)
        .unwrap_or_default()
        .lines()
        .filter(|l| l.trim() == "node_modules")
        .count()
}

fn is_link_to(link: &Path, target: &Path) -> bool {
    std::fs::symlink_metadata(link).is_ok_and(|m| m.file_type().is_symlink())
        && std::fs::read_link(link).ok().as_deref() == Some(target)
}

#[test]
fn new_worktree_gets_the_link_and_stays_clean() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    // without the link the symlink would be untracked (`node_modules/` does not match it)
    let wt = create_task_worktree(&repo, "web", "a", "task/a", "main", true).unwrap();
    let link = wt.join("node_modules");
    assert!(is_link_to(&link, &repo.join("node_modules")), "{:?}", std::fs::read_link(&link));
    assert!(link.join(".bin/x").is_file());
    assert_eq!(git(&wt, &["status", "--porcelain"]), "");
    assert_eq!(exclude_count(&repo), 1);
    assert!(agent_brain::gitops::changed_paths(&wt).unwrap().is_empty());
    // the project repo itself is clean too
    assert_eq!(git(&repo, &["status", "--porcelain"]), "");
}

#[test]
fn second_call_is_idempotent() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    let wt = create_task_worktree(&repo, "web", "a", "task/a", "main", true).unwrap();
    // the worktree exists on the right branch: reused, linked again without a change
    let again = create_task_worktree(&repo, "web", "a", "task/a", "main", true).unwrap();
    assert_eq!(again, wt);
    link_node_modules(&repo, &wt);
    link_node_modules(&repo, &wt);
    assert!(is_link_to(&wt.join("node_modules"), &repo.join("node_modules")));
    assert_eq!(exclude_count(&repo), 1);
    assert_eq!(git(&wt, &["status", "--porcelain"]), "");
}

#[test]
fn exclude_file_keeps_its_other_lines() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    // an existing exclude without a final newline
    std::fs::create_dir_all(repo.join(".git/info")).unwrap();
    std::fs::write(repo.join(".git/info/exclude"), "# mine\n*.log").unwrap();
    create_task_worktree(&repo, "web", "a", "task/a", "main", true).unwrap();
    let text = std::fs::read_to_string(repo.join(".git/info/exclude")).unwrap();
    assert_eq!(text, "# mine\n*.log\nnode_modules\n");
}

