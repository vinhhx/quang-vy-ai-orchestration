#[test]
fn worktree_with_its_own_node_modules_is_left_alone() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    let wt = create_task_worktree(&repo, "web", "a", "task/a", "main", false).unwrap();
    std::fs::create_dir_all(wt.join("node_modules")).unwrap();
    link_node_modules(&repo, &wt);
    let meta = std::fs::symlink_metadata(wt.join("node_modules")).unwrap();
    assert!(meta.file_type().is_dir() && !meta.file_type().is_symlink());
    assert_eq!(exclude_count(&repo), 0);
}

#[test]
fn old_worktree_is_linked_by_ensure_task_root() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    // a worktree made before this feature: no link yet
    let wt = create_task_worktree(&repo, "web", "old", "task/old", "main", false).unwrap();
    assert!(std::fs::symlink_metadata(wt.join("node_modules")).is_err());
    let conn = rusqlite::Connection::open_in_memory().unwrap();
    let t = task("old", Some(&wt));

    // `link_node_modules: false` in the project entry: still no link
    let off = project(&repo, serde_json::json!({"link_node_modules": false}));
    assert_eq!(ensure_task_root(&conn, &off, &repo, &t).unwrap(), wt);
    assert!(std::fs::symlink_metadata(wt.join("node_modules")).is_err());

    let on = project(&repo, serde_json::json!({}));
    assert!(on.workspace.is_worktree() && on.workspace.link_node_modules);
    assert_eq!(ensure_task_root(&conn, &on, &repo, &t).unwrap(), wt);
    assert!(is_link_to(&wt.join("node_modules"), &repo.join("node_modules")));
    assert_eq!(git(&wt, &["status", "--porcelain"]), "");
    // calling again changes nothing
    assert_eq!(ensure_task_root(&conn, &on, &repo, &t).unwrap(), wt);
    assert_eq!(exclude_count(&repo), 1);
}

#[test]
fn old_worktree_with_a_hand_made_link_gets_it_excluded() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    let wt = create_task_worktree(&repo, "web", "hand", "task/hand", "main", false).unwrap();
    std::os::unix::fs::symlink(repo.join("node_modules"), wt.join("node_modules")).unwrap();
    assert_eq!(git(&wt, &["status", "--porcelain"]).trim(), "?? node_modules");
    let conn = rusqlite::Connection::open_in_memory().unwrap();
    let on = project(&repo, serde_json::json!({}));
    ensure_task_root(&conn, &on, &repo, &task("hand", Some(&wt))).unwrap();
    assert_eq!(git(&wt, &["status", "--porcelain"]), "");
}

#[test]
fn changed_paths_ignores_the_link_even_without_the_exclude_line() {
    let _env = Env::new();
    let tmp = tempfile::tempdir().unwrap();
    let repo = project_repo(tmp.path(), true, true);
    let wt = create_task_worktree(&repo, "web", "safe", "task/safe", "main", false).unwrap();
    std::os::unix::fs::symlink(repo.join("node_modules"), wt.join("node_modules")).unwrap();
    // git sees the link (no exclude), the dirty check does not
    assert_eq!(git(&wt, &["status", "--porcelain"]).trim(), "?? node_modules");
    assert!(agent_brain::gitops::changed_paths(&wt).unwrap().is_empty());
    std::fs::write(wt.join("real.txt"), "x").unwrap();
    let paths = agent_brain::gitops::changed_paths(&wt).unwrap();
    assert_eq!(paths.into_iter().collect::<Vec<_>>(), vec!["real.txt".to_string()]);
}
